// Writes the iOS SDK's version constant from ios/package.json.
//
// Swift has no build step that could read the version at compile time, so the
// number has to be in a source file. Changesets bumps ios/package.json with
// the other packages; `pnpm version-packages` then runs this script.
// The Android build needs no such step: Gradle reads android/package.json.
//
// Run from anywhere: `node scripts/sync-native-version.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const { version } = JSON.parse(readFileSync(new URL("ios/package.json", root), "utf8"));

export function versionSwift(sdkVersion) {
  return `// Generated by scripts/sync-native-version.mjs from ios/package.json. Do not edit.

/// Information about this build of the Fish Agent SDK.
public enum FishAgentSDK {
    /// The SDK version, the same number as the JavaScript packages released with it.
    public static let version = "${sdkVersion}"
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL("ios/Sources/FishAgent/Version.swift", root);
  writeFileSync(target, versionSwift(version));
  console.log(`ios/Sources/FishAgent/Version.swift → ${version}`);
}
